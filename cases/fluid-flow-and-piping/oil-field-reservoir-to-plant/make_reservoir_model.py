"""Writes the reservoir model file of the oil field example: OILFIELD.DATA.

    python make_reservoir_model.py <output folder>

A box reservoir of 10 x 10 x 3 cells with three producers, one gas injector and one water
injector, in FIELD units, for OPM Flow. The fluid comes from the two include files of this
folder, which the Reservoir Coupling tool generated from the flowsheet: pvt_dwsim.inc (black-oil
PVT) and vfp_dwsim.inc (lift table of the wells). They are copied next to the reservoir model file.

The numbers of this reservoir model were chosen for the example. It is not a model of any real field.
"""
import os
import shutil
import sys

out_dir = sys.argv[1] if len(sys.argv) > 1 else "."
here = os.path.dirname(os.path.abspath(__file__))
os.makedirs(out_dir, exist_ok=True)
for name in ("pvt_dwsim.inc", "vfp_dwsim.inc"):
    if os.path.abspath(out_dir) != here:
        shutil.copyfile(os.path.join(here, name), os.path.join(out_dir, name))

SWC, SOR, SGC, SOGR = 0.20, 0.25, 0.04, 0.05


def swof():
    rows = []
    n = 12
    for i in range(n + 1):
        sw = SWC + (1.0 - SOR - SWC) * i / n
        s = (sw - SWC) / (1.0 - SOR - SWC)
        rows.append((sw, 0.4 * s ** 2.5, (1.0 - s) ** 2.0, 0.0))
    rows.append((1.0, 1.0, 0.0, 0.0))
    return rows


def sgof():
    rows = [(0.0, 0.0, 1.0, 0.0)]
    n = 12
    top = 1.0 - SWC - SOGR          # the oil left behind by gas
    for i in range(n + 1):
        sg = SGC + (top - SGC) * i / n
        s = (sg - SGC) / (top - SGC)
        rows.append((sg, 0.9 * s ** 2.0, (1.0 - s) ** 2.5 if i < n else 0.0, 0.0))
    return rows


def table(rows):
    return "\n".join(" %.4f %.5f %.5f %.1f" % r for r in rows) + " /"


